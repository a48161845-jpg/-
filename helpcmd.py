def _menu():
    names = list(SECTIONS)
    btns = [B(text=SECTIONS[n][0].split(" (")[0], callback_data=f"hp:{n}") for n in names]
    btns.append(B(text="📖 Всё сразу", callback_data="hp:все"))
    return KB(inline_keyboard=[btns[i:i + 2] for i in range(0, len(btns), 2)])


def _text(name):
    title, body = SECTIONS[name]
    return f"<b>{title}</b>\n\n{body}"


@cmd(".помощь", ".попощь", ".команды", ".help", "/start", "/help")
async def c_help(m, args, bot):
    a = (args or "").strip().lower()
    if a in ("все", "всё", "all"):
        for n in SECTIONS:
            await m.answer(_text(n))
        return
    for n in SECTIONS:
        if a and (a == n or n.startswith(a)):
            return await m.answer(_text(n))
    await m.answer(f"📖 <b>Помощь</b>\n\n{PFX}\n\nВыберите раздел или напишите <code>.помощь все</code>:", reply_markup=_menu())


@cb("hp")
async def on_cb(call, parts, bot):
    name = parts[1]
    if name == "все":
        for n in SECTIONS:
            await call.message.answer(_text(n))
    elif name == "меню":
        await call.message.edit_text(f"📖 <b>Помощь</b>\n\n{PFX}\n\nВыберите раздел:", reply_markup=_menu())
    elif name in SECTIONS:
        await call.message.edit_text(_text(name), reply_markup=KB(inline_keyboard=[[B(text="⬅️ Назад", callback_data="hp:меню")]]))
    await call.answer()
