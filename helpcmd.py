def _intro():
    lines = [f"📖 <b>Помощь</b>\n\n{PFX}\n\n<b>Разделы:</b>"]
    for n, (title, _) in SECTIONS.items():
        lines.append(f"{title.split(' (')[0]} — {DESC[n]}")
    lines.append("\nВыберите раздел:")
    return "\n".join(lines)


def _menu():
    btns = [B(text=SECTIONS[n][0].split(" (")[0], callback_data=f"hp:{n}") for n in SECTIONS]
    return KB(inline_keyboard=[btns[i:i + 2] for i in range(0, len(btns), 2)])


def _text(name):
    title, body = SECTIONS[name]
    return f"<b>{title}</b>\n\n{body}"


@cmd(".помощь", ".попощь", ".команды", ".help", "/start", "/help")
async def c_help(m, args, bot):
    a = (args or "").strip().lower()
    for n in SECTIONS:
        if a and (a == n or n.startswith(a)):
            return await m.answer(_text(n))
    await m.answer(_intro(), reply_markup=_menu())


@cb("hp")
async def on_cb(call, parts, bot):
    name = parts[1]
    if name == "меню":
        await call.message.edit_text(_intro(), reply_markup=_menu())
    elif name in SECTIONS:
        await call.message.edit_text(_text(name), reply_markup=KB(inline_keyboard=[[B(text="⬅️ Назад", callback_data="hp:меню")]]))
    await call.answer()
